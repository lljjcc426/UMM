// Local operation test. Requires Playwright + Chrome; no GPU or model calls.
const assert=require('node:assert/strict'),fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
let browser;
(async()=>{
 const output='private/engineering_hanzi_video/browser';fs.mkdirSync(output,{recursive:true});
 browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE,headless:true,args:['--disable-gpu']});
 const page=await browser.newPage({viewport:{width:1280,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8780/');
 await page.waitForSelector('#characters button');
 assert.equal(await page.locator('#characters button').count(),8);
 assert.match(await page.locator('#connection').textContent(),/UMM未连接/);
 await page.locator('input[name=mode][value=umm]').check();
 assert(await page.locator('#generate').isDisabled());
 const offline=await page.request.post('http://127.0.0.1:8780/api/generate',{data:{mode:'umm',character:'士'}});
 assert.equal(offline.status(),400);
 await page.locator('input[name=mode][value=preview]').check();
 await page.locator('#character').fill('猫');await page.locator('#generate').click();
 await page.waitForFunction(()=>document.querySelector('#status').classList.contains('error'));
 assert.match(await page.locator('#status').textContent(),/仅支持/);
 await page.getByRole('button',{name:'士',exact:true}).click();
 await page.locator('#generate').click();
 await page.waitForSelector('#result:not([hidden])');
 await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
 assert.equal(await page.locator('#strokes li').count(),3);
 const media=await page.locator('video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration}));
 assert.equal(media.width,512);assert.equal(media.height,512);
 assert(Math.abs(media.duration-97/24)<.05);
 const videoUrl=await page.locator('video').getAttribute('src');
 const partial=await page.request.get('http://127.0.0.1:8780'+videoUrl,{headers:{Range:'bytes=0-1023'}});
 assert.equal(partial.status(),206);assert.equal((await partial.body()).length,1024);
 await page.locator('#replay').click();
 await page.waitForFunction(()=>document.querySelector('video').currentTime>.1);
 await page.locator('video').evaluate(v=>v.pause());
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
 await download.saveAs(output+'/士-书写.mp4');
 assert(fs.statSync(output+'/士-书写.mp4').size>1000);
 await page.locator('video').evaluate(v=>new Promise(resolve=>{v.addEventListener('seeked',resolve,{once:true});v.currentTime=v.duration-.1;}));
 const finalFrame=await page.locator('video').evaluate(v=>{const c=document.createElement('canvas');c.width=512;c.height=512;const x=c.getContext('2d');x.drawImage(v,0,0);const rgb=x.getImageData(0,0,512,512).data;let dark=0;for(let i=0;i<rgb.length;i+=4)if(rgb[i]<96)dark++;return{time:v.currentTime,dark_pixels:dark};});
 assert(finalFrame.time>3.8);assert(finalFrame.dark_pixels>1000);
 await page.screenshot({path:output+'/desktop.png',fullPage:true});
 await page.locator('#imageTab').click();
 const validation=JSON.parse(fs.readFileSync('data/engineering/hanzi_video_v1/validation.json','utf8'));
 await page.locator('#image').setInputFiles(validation.output_directory+'/58eb.png');
 await page.waitForSelector('#imagePreview:not([hidden])');
 assert(await page.locator('#imagePreview').isVisible());
 assert(await page.locator('#recognize').isDisabled());
 assert(await page.locator('#generate').isDisabled());
 const license=await page.request.get('http://127.0.0.1:8780/font-license');assert.equal(license.status(),200);
 assert.match(await license.text(),/ARPHIC PUBLIC LICENSE/);
 await page.setViewportSize({width:390,height:844});await page.locator('#textTab').click();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:output+'/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await browser.close();
 const result={passed:true,characters:8,CPU_preview_playback_download:true,unsupported_character_rejected:true,
  offline_UMM_UI_and_API_rejected:true,image_upload_preview:true,image_recognition_not_simulated:true,
  license_available:true,mobile_no_horizontal_overflow:true,HTTP_range_206:true,finalFrame,media,errors,model_calls:0,screenshots:output};
 fs.writeFileSync('data/engineering/hanzi_video_v1/browser.json',JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exitCode=1;});
